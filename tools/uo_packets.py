class PacketStreamError(ValueError):
    """Base class for malformed or incomplete UO packet streams."""


class UnknownPacketError(PacketStreamError):
    """Raised when a command has no entry in the protocol length table."""


class TruncatedPacketError(PacketStreamError):
    """Raised when a packet header or declared body is incomplete."""


class UOPacket(NamedTuple):
    """One fully framed packet and its offset in the decoded stream."""

    offset: int
    command: int
    data: bytes


def split_packet_stream(data: bytes, *, allow_truncated: bool = False) -> list[UOPacket]:
    """Split a decoded stream using the UO length table.

    ``allow_truncated`` is for a live socket buffer: a trailing incomplete
    packet is left for the next recv, while unknown commands still fail
    immediately.  The default is strict and is used for completed responses
    and offline tests.
    """

    packets: list[UOPacket] = []
    offset = 0
    data_length = len(data)
    while offset < data_length:
        command = data[offset]
        packet_length: Optional[int] = UO_PACKET_LENGTHS.get(command)
        if packet_length is None:
            raise UnknownPacketError(
                f"unknown UO packet 0x{command:02x} at offset {offset}"
            )

        if packet_length < 0:
            if data_length - offset < 3:
                if allow_truncated:
                    break
                raise TruncatedPacketError(
                    f"truncated variable packet header 0x{command:02x} "
                    f"at offset {offset}"
                )
            packet_length = int.from_bytes(data[offset + 1:offset + 3], "big")
            if packet_length < 3:
                raise PacketStreamError(
                    f"invalid length {packet_length} for variable packet "
                    f"0x{command:02x} at offset {offset}"
                )

        packet_end = offset + packet_length
        if packet_end > data_length:
            if allow_truncated:
                break
            raise TruncatedPacketError(
                f"truncated packet 0x{command:02x} at offset {offset}: "
                f"need {packet_length} bytes, have {data_length - offset}"
            )

        packets.append(UOPacket(offset, command, data[offset:packet_end]))
        offset = packet_end

    return packets


def find_packet(data: bytes, command: int) -> Optional[UOPacket]:
    """Return the first complete packet with ``command`` in a stream."""

    for packet in split_packet_stream(data, allow_truncated=True):
        if packet.command == command:
            return packet
    return None
